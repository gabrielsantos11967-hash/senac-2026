def connection_settings():
    # Confere se as cinco configuracoes existem antes de tentar conectar.
    required = ("DB_HOST", "DB_PORT", "DB_NAME", "DB_USER", "DB_PASSWORD")
    missing = [name for name in required if not os.getenv(name)]
    if missing:
        raise ValueError(
            "Defina as variaveis de ambiente obrigatorias: " + ", ".join(missing)
        )

    return {
        "host": os.environ["DB_HOST"],
        "port": int(os.environ["DB_PORT"]),
        "dbname": os.environ["DB_NAME"],
        "user": os.environ["DB_USER"],
        "password": os.environ["DB_PASSWORD"],
    }


def print_rows(cursor, heading):
    # Mostra no terminal as colunas e linhas retornadas pela consulta.
    rows = cursor.fetchall()
    print(f"\n{heading}")
    if not rows:
        print("(nenhum registro)")
        return

    columns = [column.name for column in cursor.description]
    print(" | ".join(columns))
    for row in rows:
        print(" | ".join(str(value) for value in row))


def create_tables(cursor):
    # Cria as tabelas; a chave estrangeira liga cada lancamento a um setor.
    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS setor (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome VARCHAR(100) NOT NULL UNIQUE,
            descricao VARCHAR(255)
        )
        """
    )
    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS financeiro (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            descricao VARCHAR(255) NOT NULL UNIQUE,
            valor NUMERIC(10, 2) NOT NULL,
            tipo VARCHAR(50) NOT NULL,
            data DATE NOT NULL,
            conciliado BOOLEAN NOT NULL DEFAULT FALSE,
            setor_id INTEGER NOT NULL REFERENCES setor(id)
        )
        """
    )
    cursor.execute(
        """
        ALTER TABLE financeiro
        ADD COLUMN IF NOT EXISTS conciliado BOOLEAN NOT NULL DEFAULT FALSE
        """
    )


def seed_data(cursor):
    # Cadastra os setores somente se ainda nao existirem.
    cursor.execute(
        """
        INSERT INTO setor (nome, descricao)
        SELECT dados.nome, dados.descricao
        FROM (VALUES (%s, %s), (%s, %s), (%s, %s)) AS dados(nome, descricao)
        WHERE NOT EXISTS (
            SELECT 1 FROM setor existente WHERE existente.nome = dados.nome
        )
        """,
        tuple(value for setor in SETORES for value in setor),
    )

    # Cadastra lancamentos sem duplicar descricoes ja presentes na tabela.
    inserted = 0
    for lancamento in LANCAMENTOS:
        descricao, valor, tipo, data, conciliado, nome_setor = lancamento
        cursor.execute(
            """
            INSERT INTO financeiro (descricao, valor, tipo, data, conciliado, setor_id)
            SELECT %s, %s, %s, %s, %s, setor.id
            FROM setor
            WHERE setor.nome = %s
              AND NOT EXISTS (
                  SELECT 1 FROM financeiro existente
                  WHERE existente.descricao = %s
              )
            """,
            (descricao, valor, tipo, data, conciliado, nome_setor, descricao),
        )
        inserted += cursor.rowcount
    print(f"Registros novos inseridos em financeiro: {inserted}")


def run_reads(cursor):
    # Executa leituras: todos, filtrados, ordenados e relacionados por JOIN.
    cursor.execute(
        """
        SELECT id, descricao, valor, tipo, data, conciliado, setor_id
        FROM financeiro
        """
    )
    print_rows(cursor, "READ - todos os lancamentos")

    cursor.execute(
        """
        SELECT id, descricao, valor, tipo, data, conciliado, setor_id
        FROM financeiro
        WHERE tipo = %s
        """,
        ("Despesa",),
    )
    print_rows(cursor, "READ - lancamentos filtrados (somente despesas)")

    cursor.execute(
        """
        SELECT id, descricao, valor, tipo, data, conciliado, setor_id
        FROM financeiro
        ORDER BY data
        """
    )
    print_rows(cursor, "READ - lancamentos ordenados por data")

    cursor.execute(
        """
        SELECT
            financeiro.id AS id_lancamento,
            financeiro.descricao AS lancamento,
            financeiro.valor,
            financeiro.tipo,
            financeiro.data,
            financeiro.conciliado,
            setor.nome AS setor_responsavel
        FROM financeiro
        INNER JOIN setor ON setor.id = financeiro.setor_id
        ORDER BY financeiro.data
        """
    )
    print_rows(cursor, "EXTRA - lancamentos com seus setores (JOIN)")


def run_update(cursor, connection):
    # Consulta antes e depois para mostrar que o UPDATE altera o registro certo.
    descricao = "Manutencao de Servidores"
    cursor.execute(
        "SELECT id, descricao, valor FROM financeiro WHERE descricao = %s",
        (descricao,),
    )
    print_rows(cursor, "UPDATE - antes")

    cursor.execute(
        """
        UPDATE financeiro
        SET valor = %s
        WHERE descricao = %s
        RETURNING id, descricao, valor
        """,
        (1750.00, descricao),
    )
    print_rows(cursor, "UPDATE - registro alterado")
    # Confirma a alteracao para que ela seja gravada permanentemente.
    connection.commit()

    cursor.execute(
        "SELECT id, descricao, valor FROM financeiro WHERE descricao = %s",
        (descricao,),
    )
    print_rows(cursor, "UPDATE - depois do commit")


def run_delete(cursor, connection):
    # Consulta antes e depois para comprovar a exclusao com condicao WHERE.
    descricao = "Auditoria Contabil"
    cursor.execute(
        "SELECT id, descricao, valor FROM financeiro WHERE descricao = %s",
        (descricao,),
    )
    print_rows(cursor, "DELETE - antes")

    cursor.execute(
        """
        DELETE FROM financeiro
        WHERE descricao = %s
        RETURNING id, descricao, valor
        """,
        (descricao,),
    )
    print_rows(cursor, "DELETE - registro excluido")
    # Confirma a exclusao no banco.
    connection.commit()

    cursor.execute(
        "SELECT id, descricao, valor FROM financeiro WHERE descricao = %s",
        (descricao,),
    )
    print_rows(cursor, "DELETE - depois do commit")


def main():
    # O .env fica na raiz, mesmo com este script dentro da pasta python.
    env_file = Path(__file__).resolve().parent.parent / ".env"
    load_dotenv(dotenv_path=env_file)
    settings = connection_settings()
    # Exibe dados nao sigilosos; a senha nunca aparece no terminal.
    print(
        "Conectando ao PostgreSQL: "
        f"host={settings['host']}, port={settings['port']}, "
        f"database={settings['dbname']}, user={settings['user']}"
    )

    # Os gerenciadores with fecham cursor e conexao mesmo se ocorrer erro.
    with psycopg.connect(**settings) as connection:
        print("Conexao estabelecida.")
        with connection.cursor() as cursor:
            create_tables(cursor)
            seed_data(cursor)
            connection.commit()
            print("Tabelas e dados iniciais confirmados (commit).")

            run_reads(cursor)
            run_update(cursor, connection)
            run_delete(cursor, connection)

    print("Conexao encerrada.")


if __name__ == "__main__":
    # Mostra erros de configuracao ou do PostgreSQL sem ocultar a causa.
    try:
        main()
    except (ValueError, psycopg.Error) as error:
        print(f"Erro ao executar o CRUD: {error}", file=sys.stderr)
        raise
