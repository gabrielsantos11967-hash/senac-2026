-- EXTRA: relacionamento entre lancamentos e setores.
SELECT
    financeiro.id AS id_lancamento,
    financeiro.descricao AS lancamento,
    financeiro.valor,
    financeiro.tipo,
    financeiro.data,
    financeiro.conciliado,
    setor.nome AS setor_responsavel
FROM financeiro
INNER JOIN setor ON setor.id = financeiro.setor_id
ORDER BY financeiro.data;
