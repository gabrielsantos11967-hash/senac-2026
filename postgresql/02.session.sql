-- Banco PostgreSQL: controle de lancamentos financeiros por setor.
-- Execute no SQLTools para conferir a estrutura, os dados e as operacoes CRUD.

CREATE TABLE IF NOT EXISTS setor (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS financeiro (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL UNIQUE,
    valor NUMERIC(10, 2) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    data DATE NOT NULL,
    conciliado BOOLEAN NOT NULL DEFAULT FALSE,
    setor_id INTEGER NOT NULL REFERENCES setor(id)
);

-- Compatibilidade com a tabela criada pela versao anterior deste arquivo.
ALTER TABLE financeiro
    ADD COLUMN IF NOT EXISTS conciliado BOOLEAN NOT NULL DEFAULT FALSE;

INSERT INTO setor (nome, descricao)
SELECT dados.nome, dados.descricao
FROM (VALUES
    ('Tecnologia da Informacao', 'Desenvolvimento, suporte e infraestrutura'),
    ('Recursos Humanos', 'Gestao de pessoas, folha e recrutamento'),
    ('Financeiro', 'Contabilidade, faturamento e fluxo de caixa')
) AS dados(nome, descricao)
WHERE NOT EXISTS (
    SELECT 1 FROM setor existente WHERE existente.nome = dados.nome
);

INSERT INTO financeiro (descricao, valor, tipo, data, conciliado, setor_id)
SELECT dados.descricao, dados.valor, dados.tipo, dados.data, dados.conciliado, setor.id
FROM (VALUES
    ('Manutencao de Servidores', 1500.00, 'Despesa', DATE '2026-10-01', FALSE, 'Tecnologia da Informacao'),
    ('Treinamento de Equipe', 3000.00, 'Despesa', DATE '2026-10-10', TRUE, 'Recursos Humanos'),
    ('Venda de Software B2B', 15000.00, 'Receita', DATE '2026-10-15', TRUE, 'Tecnologia da Informacao'),
    ('Auditoria Contabil', 4500.00, 'Despesa', DATE '2026-10-20', FALSE, 'Financeiro'),
    ('Consultoria de Infraestrutura', 2200.00, 'Despesa', DATE '2026-10-25', FALSE, 'Tecnologia da Informacao')
) AS dados(descricao, valor, tipo, data, conciliado, nome_setor)
JOIN setor ON setor.nome = dados.nome_setor
WHERE NOT EXISTS (
    SELECT 1 FROM financeiro existente WHERE existente.descricao = dados.descricao
);

-- READ: todos os lancamentos.
SELECT id, descricao, valor, tipo, data, conciliado, setor_id
FROM financeiro;

-- READ: filtro com WHERE.
SELECT id, descricao, valor, tipo, data, conciliado, setor_id
FROM financeiro
WHERE tipo = 'Despesa';

-- READ: ordenacao com ORDER BY.
SELECT id, descricao, valor, tipo, data, conciliado, setor_id
FROM financeiro
