1. Criação da tabela de Setores
CREATE TABLE setor (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255)
);

2. Criação da tabela Financeiro (com relacionamento para a tabela Setor)
CREATE TABLE financeiro (
   id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   descricao VARCHAR(255) NOT NULL,
   valor NUMERIC(10, 2) NOT NULL,
   tipo VARCHAR(50) NOT NULL, -- Ex: 'Receita' ou 'Despesa'
   data DATE NOT NULL,
   setor_id INT,
   CONSTRAINT fk_setor FOREIGN KEY (setor_id) REFERENCES setor(id)
);

