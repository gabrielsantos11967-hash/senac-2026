-- 5. Consulta (Query) para unir as informações das duas tabelas
SELECT 
   f.id AS id_transacao,
   f.descricao AS transacao,
    f.valor,
   f.tipo,
    TO_CHAR(f.data, 'DD/MM/YYYY') AS data_formatada,
    s.nome AS setor_responsavel
FROM financeiro f
INNER JOIN setor s ON f.setor_id = s.id;